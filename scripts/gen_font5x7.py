# Fallback glyph for any character outside the printable ASCII range.
FALLBACK = ["#####", "#   #", "#   #", "#   #", "#   #", "#   #", "#####"]

FIRST = 0x20
LAST = 0x7E


def glyph_bytes(art: list[str]) -> list[int]:
    cols = [0] * 5
    for row in range(7):
        line = art[row] if row < len(art) else "     "
        for col in range(5):
            if col < len(line) and line[col] == "#":
                cols[col] |= 1 << row
    return cols


def main() -> None:
    out = ["// Auto-generated by scripts/gen_font5x7.py. Do not edit by hand.",
           "// A 5x7 column-major bitmap font for printable ASCII (0x20..0x7E).",
           "// Five bytes per glyph; bit 0 is the top row. See docs/INKKIT_GAPS.md.",
           "#pragma once", "", "#include <cstdint>", "", "namespace inkquest {", "",
           f"constexpr uint8_t kFontFirst = 0x{FIRST:02X};",
           f"constexpr uint8_t kFontLast = 0x{LAST:02X};",
           "constexpr int kFontWidth = 5;",
           "constexpr int kFontHeight = 7;", "",
           "// One row of 5 bytes per glyph, indexed by (codepoint - kFontFirst).",
           "constexpr uint8_t kFont5x7[][5] = {"]

    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        art = GLYPHS.get(ch, FALLBACK)
        cols = glyph_bytes(art)
        label = ch if ch not in ("\\",) else "backslash"
        out.append("    {" + ", ".join(f"0x{b:02X}" for b in cols) + f"}},  // 0x{code:02X} {label}")

    out += ["};", "",
            "// The fallback glyph (a filled box) for codepoints outside the table.",
            "constexpr uint8_t kFontFallback[5] = {" +
            ", ".join(f"0x{b:02X}" for b in glyph_bytes(FALLBACK)) + "};",
            "", "}  // namespace inkquest", ""]

    dest = Path(__file__).resolve().parents[1] / "src" / "device" / "Font5x7.h"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {dest} ({LAST - FIRST + 1} glyphs)")


if __name__ == "__main__":
    main()
